"""Writes music/playlist.js: the list of tracks the page plays, in order, on a loop.

The page cannot list a folder by itself (especially when opened straight from disk), so it loads this
tiny script instead. The server rewrites it on every start; run it by hand after adding or removing music:

    python -m ai_related.playlist
"""
import json
import re
from pathlib import Path

MUSIC_DIR = Path(__file__).resolve().parents[2] / "music"
AUDIO_EXT = {".mp3", ".ogg", ".wav", ".m4a", ".aac", ".flac", ".opus"}


def _natural(name: str) -> list:
    """"2. a" sorts before "10. b"."""
    return [int(t) if t.isdigit() else t.casefold() for t in re.split(r"(\d+)", name)]


def tracks() -> list[str]:
    if not MUSIC_DIR.is_dir():
        return []
    return sorted((p.name for p in MUSIC_DIR.iterdir() if p.suffix.lower() in AUDIO_EXT), key=_natural)


def write_playlist() -> list[str]:
    names = tracks()
    if MUSIC_DIR.is_dir():
        (MUSIC_DIR / "playlist.js").write_text(
            "// generated by `python -m ai_related.playlist` — do not edit by hand\n"
            f"window.MUSIC_PLAYLIST = {json.dumps(names, ensure_ascii=False, indent=2)};\n", encoding="utf-8")
    return names


if __name__ == "__main__":
    found = write_playlist()
    print(f"{len(found)} track(s) written to {MUSIC_DIR / 'playlist.js'}")
    for n in found:
        print("  ", n)
